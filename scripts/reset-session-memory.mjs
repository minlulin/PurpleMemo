#!/usr/bin/env node
/**
 * reset-session-memory.mjs
 * Overwrites docs/SESSION_MEMORY.md with a fresh template.
 * Purpose: prevent a huge accumulating memory file exhausting agent context.
 * Usage: npm run session:reset  (alias: npm run memory:reset)
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const target = resolve(root, "docs/SESSION_MEMORY.md");

const now = new Date().toISOString().split("T")[0];

const template = `# SESSION MEMORY — ${now}

> This file is **rewritten fresh every session** via \`npm run session:reset\`.
> Never append indefinitely — overwrite to keep it small. Agent should keep
> only what matters for the next session.

## Current Goal
- [ ] (fill in)

## What Was Done (last session)
- (fill in)

## Decisions & Constraints
- Single source of truth: \`docs/PLAN.md\`. One phase at a time; never start the next phase before the current gate is green.
- Never \`git push --no-verify\`. The Progress log's gate column is the only CI evidence this project has.

## Open / Next
- [ ] (fill in)

## How to reset
\`\`\`bash
npm run session:reset
# edit file with the new session summary before committing
\`\`\`

---
Generated by scripts/reset-session-memory.mjs — edit after reset with the current session summary.
`;

await mkdir(dirname(target), { recursive: true });
await writeFile(target, template, "utf8");
console.log(`Reset ${target} (${template.length} bytes)`);
console.log("  Now edit it with the fresh session summary before committing.");
